"""Generate the decorative name waveform + Praat-style syllable tier shown on the home page.

Writes layouts/_partials/waveform.html. The waveform is synthesized from a simple
segment model of the name (fricatives = noise, vowels = loud periodic bursts,
glottal stop = brief silence). If a real recording exists later, pass --wav to
draw its actual amplitude envelope instead.

    python3 scripts/make_waveform.py
    python3 scripts/make_waveform.py --wav static/audio/name/samira-hamzehei.wav
"""
import argparse
import math
import random
import struct
import wave
from pathlib import Path

W, WAVE_H, TIER_Y, TIER_H = 640, 56, 66, 26
X0, X1 = 8, 632
BAR_W, STEP = 2.0, 3.2

# (label, x_start, x_end, segments) — segments: (fraction_end, kind, amplitude)
SYLLABLES = [
    ("sæ", 8, 96, [(0.38, "noise", 0.30), (1.0, "vowel", 0.82)]),
    ("mi", 96, 176, [(0.30, "nasal", 0.42), (1.0, "vowel", 0.70)]),
    ("ˈɾɒ", 176, 288, [(0.12, "dip", 0.16), (1.0, "vowel", 1.00)]),
    ("", 288, 318, [(1.0, "silence", 0.0)]),
    ("hæm", 318, 420, [(0.24, "noise", 0.14), (0.76, "vowel", 0.90), (1.0, "nasal", 0.40)]),
    ("ze", 420, 500, [(0.36, "noise", 0.34), (1.0, "vowel", 0.74)]),
    ("ˈʔi", 500, 632, [(0.08, "silence", 0.0), (1.0, "vowel", 0.96)]),
]


def synth_amplitudes(n_bars):
    rng = random.Random(7)
    amps = []
    for i in range(n_bars):
        x = X0 + i * STEP + BAR_W / 2
        amp = 0.0
        for _, a, b, segs in SYLLABLES:
            if a <= x < b:
                u = (x - a) / (b - a)
                start = 0.0
                for end, kind, level in segs:
                    if u < end:
                        v = (u - start) / (end - start)
                        if kind == "vowel":
                            amp = level * math.sin(math.pi * v) ** 0.55
                            amp *= 0.86 + 0.14 * math.sin(i * 1.9)
                            amp *= 0.9 + 0.2 * rng.random()
                        elif kind == "noise":
                            amp = level * (0.45 + 0.55 * rng.random())
                        elif kind == "nasal":
                            amp = level * (0.85 + 0.15 * math.sin(math.pi * v))
                        elif kind == "dip":
                            amp = level
                        break
                    start = end
                break
        amps.append(min(1.0, amp))
    return amps


def wav_amplitudes(path, n_bars):
    with wave.open(str(path)) as w:
        frames = w.readframes(w.getnframes())
        width, channels = w.getsampwidth(), w.getnchannels()
    if width != 2:
        raise SystemExit("expected 16-bit PCM WAV")
    samples = struct.unpack(f"<{len(frames) // 2}h", frames)[::channels]
    chunk = max(1, len(samples) // n_bars)
    peaks = [max((abs(s) for s in samples[i * chunk:(i + 1) * chunk]), default=0) for i in range(n_bars)]
    top = max(peaks) or 1
    return [p / top for p in peaks]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wav", type=Path)
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent / "layouts/_partials/waveform.html")
    args = ap.parse_args()

    n_bars = int((X1 - X0) / STEP)
    amps = wav_amplitudes(args.wav, n_bars) if args.wav else synth_amplitudes(n_bars)
    mid = WAVE_H / 2
    bars = []
    for i, a in enumerate(amps):
        h = max(1.4, a * (WAVE_H - 4))
        bars.append(f'<rect x="{X0 + i * STEP:.1f}" y="{mid - h / 2:.1f}" width="{BAR_W}" height="{h:.1f}" rx="1"/>')

    tier = [f'<rect class="tier-box" x="{X0}" y="{TIER_Y}" width="{X1 - X0}" height="{TIER_H}" rx="3"/>']
    for label, a, b, _ in SYLLABLES:
        if a > X0:
            tier.append(f'<line class="tier-boundary" x1="{a}" y1="{TIER_Y}" x2="{a}" y2="{TIER_Y + TIER_H}"/>')
            tier.append(f'<line class="wave-boundary" x1="{a}" y1="2" x2="{a}" y2="{WAVE_H - 2}"/>')
        if label:
            tier.append(f'<text class="tier-label" x="{(a + b) / 2:.1f}" y="{TIER_Y + 17.5}" text-anchor="middle">{label}</text>')

    svg = (
        "{{/* Generated by scripts/make_waveform.py — edit the script, not this file. */}}\n"
        f'<svg class="name-wave" viewBox="0 0 {W} {TIER_Y + TIER_H + 2}" role="img" '
        'aria-label="Decorative waveform of the name, with a syllable-by-syllable IPA annotation tier" '
        'lang="fa-fonipa" focusable="false">\n'
        '<defs><linearGradient id="wave-gradient" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="640" y2="0">'
        '<stop offset="0" style="stop-color:var(--wave-1)"/>'
        '<stop offset=".55" style="stop-color:var(--wave-2)"/>'
        '<stop offset="1" style="stop-color:var(--wave-3)"/></linearGradient></defs>\n'
        '<g class="wave-bars" fill="url(#wave-gradient)">' + "".join(bars) + "</g>\n"
        '<g class="wave-tier">' + "".join(tier) + "</g>\n</svg>\n"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(svg, encoding="utf-8")
    print(f"wrote {args.out} ({n_bars} bars)")


if __name__ == "__main__":
    main()
